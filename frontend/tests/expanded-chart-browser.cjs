const {chromium}=require(process.env.SIMTRA_PLAYWRIGHT || 'playwright');
const assert=require('node:assert/strict');
(async()=>{const browser=await chromium.launch({channel:'chrome',headless:true});try{
 const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
 const errors=[];page.on('pageerror',e=>{errors.push(String(e));console.error(String(e));});
 page.setDefaultTimeout(15000);
 await page.goto((process.env.SIMTRA_TEST_BASE||'http://127.0.0.1:5198')+'/?demo=1');
 await page.waitForFunction(async()=>(await import(document.querySelector('script[type=module]').src)).state.phase==='idle');
 await page.locator('#ask-input').fill('I want to raise Chipotle bowl prices in SF by 20%');await page.locator('#ask-submit').click();
 await page.locator('[data-action=expand-chart]').waitFor();
 assert.match(await page.locator('.ex-y-label').innerText(),/Estimated audience who would buy \(%\)/);
 await page.locator('[data-action=expand-chart]').click();
 const dialog=page.getByRole('dialog',{name:'Expanded price chart'});await dialog.waitFor();
 assert.ok((await dialog.boundingBox()).width>900);
 assert.equal(await dialog.locator('.ex-curve [data-scenario]').count(),21);
 await dialog.locator('.ex-curve .ex-hit').first().click();
 const selected=await dialog.locator('.ex-curve [aria-pressed=true]').getAttribute('data-scenario');
 assert.equal(await page.locator('#research-workspace .ex-curve [aria-pressed=true]').getAttribute('data-scenario'),selected);
 await dialog.locator('[data-curve=location][aria-pressed=false]').click();
 const location=await dialog.locator('[data-curve=location][aria-pressed=true]').getAttribute('data-value');
 assert.equal(await page.locator('#research-workspace [data-curve=location][aria-pressed=true]').getAttribute('data-value'),location);
 await page.screenshot({path:'/tmp/simtra-expanded-chart.png'});
 await page.keyboard.press('Escape');assert.equal(await dialog.isVisible(),false);
 assert.equal(await page.locator('[data-action=expand-chart]').evaluate(el=>el===document.activeElement),true);
 await page.setViewportSize({width:390,height:844});await page.locator('[data-action=expand-chart]').click();
 const rect=await dialog.boundingBox();assert.ok(rect.x>=0&&rect.x+rect.width<=390);
 await dialog.locator('[data-action=close-chart]').click();assert.equal(await dialog.isVisible(),false);
 assert.deepEqual(errors,[]);console.log('PASS explicit axes, expanded chart, synchronized price/location selection, Escape and focus return, mobile bounds');
}finally{await browser.close();}})().catch(e=>{console.error(e);process.exit(1)});
