// Verify the result panel and map remain one interactive workspace.
const {chromium}=require(process.env.SIMTRA_PLAYWRIGHT || 'playwright');
const assert=require('node:assert/strict');
(async()=>{const browser=await chromium.launch({channel:'chrome',headless:true});try{
 const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
 const errors=[];page.on('pageerror',e=>errors.push(String(e)));
 await page.goto((process.env.SIMTRA_TEST_BASE||'http://127.0.0.1:5198')+'/?demo=1');
 await page.evaluate(async()=>{window.panelTestApp=await import(document.querySelector('script[type=module]').src);});
 await page.waitForFunction(()=>panelTestApp.state.phase==='idle');
 await page.locator('#ask-input').fill('I want to raise Chipotle bowl prices in SF by 20%');
 await page.locator('#ask-submit').click();
 await page.locator('.ex-matrix-cell').first().waitFor({timeout:30000});
 const geometry=await page.locator('#research-workspace').evaluate(el=>({rect:el.getBoundingClientRect().toJSON(),body:parseFloat(getComputedStyle(el).fontSize),label:parseFloat(getComputedStyle(el.querySelector('.ex-curve .pc-axis')).fontSize)}));
 assert.ok(geometry.rect.x>800 && geometry.rect.width<=560,'results dock on the right, exposing the map');
 assert.ok(geometry.body>=16 && geometry.label>=18,'body and chart labels are readable');
 assert.equal(await page.locator('.ex-matrix-cell').count(),24);
 assert.equal(await page.locator('.ex-design-node').count(),3);
 assert.equal(await page.locator('select[data-curve]').count(),0);
 assert.equal(await page.locator('.ex-faces').innerText(),'');
 const locations=page.locator('button[data-curve="location"]');
 assert.equal(await locations.count(),2);
 const nextLocation=page.locator('button[data-curve="location"][aria-pressed="false"]').first();
 const nextValue=await nextLocation.getAttribute('data-value');await nextLocation.click();
 assert.equal(await page.locator('button[data-curve="location"][aria-pressed="true"]').getAttribute('data-value'),nextValue);
 await page.locator('.ex-matrix-cell[data-scenario="0"]').click();
 assert.equal(await page.locator('.ex-curve [aria-pressed="true"]').getAttribute('data-scenario'),'0');
 for(const mode of ['factor','income','age','response']) {
  await page.locator('#experiment-map-color').selectOption(mode);
  assert.equal(await page.evaluate(()=>panelTestApp.map.mapColorMode),mode);
  const labels=await page.locator('.ex-map-key > span').allTextContents();
  assert.deepEqual(labels,await page.evaluate(()=>panelTestApp.map.mapColorLegend.map(x=>x.label)));
 }
 await page.locator('.ex-matrix-cell[data-scenario="5"]').click();
 await page.locator('.ex-comparison').scrollIntoViewIfNeeded();
 await page.screenshot({path:'/tmp/simtra-visual-matrix.png'});
 const hit=await page.evaluate(()=>{
  const {map,state}=panelTestApp;
  const a=map.agents[Math.floor(map.agents.length/2)];
  for(const sprite of map.agents)sprite.speed=0;
  map.cam={x:a.wx,y:a.wy,zoom:4};map.camTarget={...map.cam};map.zoomedIn=true;
  const point=map.worldToScreen(a.wx,a.wy),x=point.x,y=point.y-8;
  const sprite=map._hitSprite(x,y);if(!sprite)throw Error('No resident under test pointer');
  const r=map.canvas.getBoundingClientRect();
  return {x:r.left+x,y:r.top+y,name:state.rawResidents.find(p=>p.id===sprite.seed).name};
 });
 await page.mouse.click(hit.x,hit.y);
 await page.locator('#experiment-person:not([hidden])').waitFor();
 assert.equal(await page.locator('.ex-person-head strong').innerText(),hit.name);
 assert.equal(await page.locator('.pr-price-point').count(),6);
 assert.equal(await page.locator('.pr-person-metric').count(),1);
 assert.equal(await page.locator('.ex-person-result').count(),0);
 await page.locator('#experiment-person').scrollIntoViewIfNeeded();
 await page.screenshot({path:'/tmp/simtra-visual-persona.png'});
 await page.setViewportSize({width:390,height:844});
 await page.locator('#research-workspace').evaluate(el=>el.scrollTop=0);
 const mobile=await page.locator('#research-workspace').evaluate(el=>({rect:el.getBoundingClientRect().toJSON(),scroll:el.scrollWidth,client:el.clientWidth}));
 assert.equal(mobile.scroll,mobile.client);assert.ok(mobile.rect.x>=0&&mobile.rect.right<=390&&mobile.rect.bottom<=844);
 await page.locator('.ex-comparison').scrollIntoViewIfNeeded();
 await page.screenshot({path:'/tmp/simtra-visual-mobile.png'});
 assert.deepEqual(errors,[]);
 console.log('PASS right results panel, larger text, actual map click selects matching resident, 24-cell comparison, location pills, four color modes, readable persona and mobile bounds');
}finally{await browser.close();}})().catch(e=>{console.error(e);process.exit(1)});
